@UIApplicationMain
class AppDelegate: UIResponder, UIApplicationDelegate, UNUserNotificationCenterDelegate {

    var window: UIWindow?

    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        UNUserNotificationCenter.current().delegate = self
        // Widget and Live Activity buttons can launch the app in the background: make sure their
        // commands still reschedule alerts, even before the web layer has loaded.
        if CadenceActions.appHook == nil {
            CadenceActions.appHook = { _, _ in DispatchQueue.main.async { Controller.refresh(); CadencePlugin.emitActions() } }
        }
        return true
    }

    // While Cadence is open it shows its own in-app alerts, so system banners only appear for the timer.
    func userNotificationCenter(_ center: UNUserNotificationCenter, willPresent notification: UNNotification,
                                withCompletionHandler completionHandler: @escaping (UNNotificationPresentationOptions) -> Void) {
        let kind = notification.request.content.userInfo["kind"] as? String
        completionHandler(kind == "phase" ? [.banner, .sound] : [])
    }

    func userNotificationCenter(_ center: UNUserNotificationCenter, didReceive response: UNNotificationResponse,
                                withCompletionHandler completionHandler: @escaping () -> Void) {
        let info = response.notification.request.content.userInfo
        switch response.actionIdentifier {
        case "timerToggle", "timerSkip", "eyeDone", "eyeSnooze":
            CadenceActions.handle(response.actionIdentifier)
        case "taskDone":
            CadenceActions.handle("taskDone", arg: info["taskId"] as? String)
        default:
            let kind = info["kind"] as? String
            CadencePlugin.open(kind == "eye" ? "screenBreak" : kind == "reminder" ? "tasks" : "focus")
        }
        completionHandler()
    }

